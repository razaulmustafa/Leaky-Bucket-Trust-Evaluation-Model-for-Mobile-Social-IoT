def get_trust_band(tau):
    """Maps 4-bit token count (0-15) to text labels exactly as defined in the manuscript."""
    if tau <= 2: return "Rapid Quarantine"
    if tau == 3: return "Black List"
    if 4 <= tau <= 7: return "Grey List"
    if tau == 8: return "Neutral Baseline"
    if 9 <= tau <= 11: return "Probationary"
    if 12 <= tau <= 13: return "Cautious Acceptance"
    if tau == 14: return "Trusted Service Provider"
    if tau >= 15: return "Privileged Service Provider"
    return "Unknown"

def apply_lbt(group):
    # Sort chronologically to preserve temporal causality
    group = group.sort_values('POSIX')

    tau = 8 # Start at Neutral Baseline (Strictly Integer)
    last_time = group['POSIX'].iloc[0]

    bands = []
    tau_history = [] # Good to track the exact integer for plotting later

    for _, row in group.iterrows():
        # A. Temporal Leakage (1 token per minute of silence)
        minutes_passed = int((row['POSIX'] - last_time) // 60)
        if minutes_passed > 0:
            tau -= minutes_passed
            tau = max(0, tau) # Ensure leakage doesn't drop below 0 before interaction

        # B. Interaction Outcome (SYNTHETIC ADVERSARY LOGIC)
        # We completely ignore t_t0 and x_x0 to avoid circular logic.
        # Instead, we evaluate based on the ground truth injected earlier.

        if row['Target_Behavior'] == 'Honest':
            # Honest nodes succeed almost always (allow 2% natural network drop rate for realism)
            is_success = np.random.rand() > 0.02
        else:
            # Malicious: Let's model an "On-Off Attacker" who complies 50% of the time
            # to try and trick the system, as mentioned in your manuscript.
            is_success = np.random.rand() > 0.50

        # Apply Asymmetric Penalty
        if is_success:
            tau += 1
        else:
            tau -= 2

        # C. Clamp Limits (Strictly 0 to 15 to match the 4-bit hardware limit)
        tau = max(0, min(15, tau))

        # Record Result
        bands.append(get_trust_band(tau))
        tau_history.append(tau)
        last_time = row['POSIX']

    group['LBT_Band'] = bands
    group['Tau'] = tau_history
    return group

